/// Этапы входа в аккаунт
enum AuthStep {
  /// Ввод имени пользователя (только для регистрации_
  enterName,
  /// Ввод идентификатора
  enterIdentifier,
  /// Ввод пароля
  enterPassword,
  /// Пользователь авторизовался
  authenticated,
  /// Заполнение недостоющих/необязательных деталей (может быть пропущен)
  registerDetails
}